export const getPlaceIcon = (iconId?: PlaceIconId | null) => {
    return PLACE_ICONS.find(icon => icon.id === iconId) ?? null
}

export const getPlaceIconName = (iconId: PlaceIconId) => {
    return iconId
        .split('-')
        .map(part => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
        .join(' ')
}
